import argparse
from pathlib import Path

import numpy as np

from train_clap import FFT_SIZE, HANN, MEL


def main():
    parser = argparse.ArgumentParser(description="Export saved clap weights and spectral tables to C++.")
    parser.add_argument("model", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    angle = -2 * np.pi * np.arange(FFT_SIZE // 2) / FFT_SIZE
    arrays = {"Hann": HANN, "Mel": MEL, "TwiddleReal": np.cos(angle), "TwiddleImag": np.sin(angle)}
    expected = {"mean": (240,), "scale": (240,), "w1": (240, 16), "b1": (16,), "w2": (16,), "b2": (1,)}
    thresholds = {"min_score": 0.0, "anchor_score": 3.0}
    with np.load(args.model) as model:
        for name, shape in expected.items():
            if model[name].shape != shape or not np.isfinite(model[name]).all():
                parser.error(f"Invalid weights: {name}")
            arrays[name.capitalize()] = model[name]
        for name in thresholds:
            if name in model:
                value = model[name]
                if value.shape != () or not np.isfinite(value):
                    parser.error(f"Invalid threshold: {name}")
                thresholds[name] = float(value)
    if thresholds["anchor_score"] < thresholds["min_score"]:
        parser.error("The anchor score must be at least the minimum score")
    lines = ["#pragma once", "", f"// Generated by tools/export_clap.py from {args.model.name}.", "namespace ClapModel {"]
    lines.append(f"constexpr float kMinScore = {thresholds['min_score']:.8e}f;")
    lines.append(f"constexpr float kAnchorScore = {thresholds['anchor_score']:.8e}f;")
    nonzero_bins = [np.flatnonzero(band) for band in MEL]
    lines.append("constexpr int kMelFirstBin[] = {" + ", ".join(str(bins[0]) for bins in nonzero_bins) + "};")
    lines.append("constexpr int kMelEndBin[] = {" + ", ".join(str(bins[-1] + 1) for bins in nonzero_bins) + "};")
    for name, values in arrays.items():
        flattened = values.astype(np.float32).ravel()
        lines.append(f"constexpr float k{name}[{len(flattened)}] = {{")
        for offset in range(0, len(flattened), 8):
            lines.append("    " + ", ".join(f"{value:.8e}f" for value in flattened[offset : offset + 8]) + ",")
        lines.append("};")
    lines.append("}  // namespace ClapModel")
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
